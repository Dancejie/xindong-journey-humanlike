/** UI text only: game identifiers and stored state always come from the server. */
export function t(chinese: string, ...values: unknown[]): string {
  const text = isEnglish ? ENGLISH[chinese] ?? chinese : chinese
  return text.replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ''))
}

export function genderLabel(gender?: string): string {
  if (gender === '男性' || gender === 'male' || gender === 'Male') return t('男性')
  if (gender === '女性' || gender === 'female' || gender === 'Female') return t('女性')
  return gender || t('嘉宾')
}

