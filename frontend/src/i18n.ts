export type GameLanguage = 'en' | 'zh-CN'
const LANGUAGE_STORAGE_KEY = 'heart-journey-language'

function normalizeLanguage(value: string | null | undefined): GameLanguage | null {
  if (/^en(?:-|$)/i.test(value || '')) return 'en'
  if (/^zh(?:-|$)/i.test(value || '')) return 'zh-CN'
  return null
}

function initialLanguage(): GameLanguage {
  const explicit = normalizeLanguage(new URLSearchParams(location.search).get('lang'))
  if (explicit) {
    try { localStorage.setItem(LANGUAGE_STORAGE_KEY, explicit) } catch { /* In-memory language still works. */ }
    return explicit
  }
  try {
    const saved = normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY))
    if (saved) return saved
  } catch { /* Private browsing can deny storage. */ }
  return /^zh(?:-|$)/i.test(navigator.language) ? 'zh-CN' : 'en'
}

export const gameLanguage = initialLanguage()
export const isEnglish = gameLanguage === 'en'

export function changeLanguage(language: GameLanguage) {
  if (language === gameLanguage) return
  try { localStorage.setItem(LANGUAGE_STORAGE_KEY, language) } catch { /* The URL also persists the choice. */ }
  const url = new URL(location.href)
  url.searchParams.set('lang', language)
  location.assign(url.toString())
}

